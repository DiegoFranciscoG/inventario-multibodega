-- Operación: costo promedio por producto, movimientos y kárdex.
-- Reglas: R-01..R-04 (costo promedio NIC 2), R-06 (kárdex inmutable), R-08 (transferencia), R-10, R-22 (documento de referencia).

CREATE TABLE product_cost (
    product_id       bigint        PRIMARY KEY REFERENCES product (id),
    quantity_on_hand numeric(18,4) NOT NULL DEFAULT 0,
    total_value      numeric(20,4) NOT NULL DEFAULT 0,
    average_cost     numeric(20,6) NOT NULL DEFAULT 0,
    last_movement_at timestamptz,
    version          bigint        NOT NULL DEFAULT 0,
    CONSTRAINT ck_product_cost_values CHECK (quantity_on_hand >= 0 AND total_value >= 0 AND average_cost >= 0)
);

CREATE TABLE document_type (
    code   varchar(4)  PRIMARY KEY,
    name   varchar(80) NOT NULL,
    source varchar(8)  NOT NULL,
    CONSTRAINT ck_document_type_source CHECK (source IN ('SRI', 'INTERNAL'))
);

