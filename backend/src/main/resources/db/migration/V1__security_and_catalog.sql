-- Seguridad (roles y usuarios) y catálogo de productos.
-- Reglas: R-11 (GTIN normalizado a 14 dígitos), R-12 (conversiones), R-13, R-20 (clase ABC), R-23 (UNECE Rec. 20), R-25.

CREATE TABLE role (
    code        varchar(20)  PRIMARY KEY,
    name        varchar(60)  NOT NULL,
    description varchar(255)
);

INSERT INTO role (code, name, description) VALUES
    ('ADMIN',      'Administrador', 'Gestiona usuarios, catálogos y configuración'),
    ('SUPERVISOR', 'Supervisor',    'Registra ajustes y aprueba conteos cíclicos'),
    ('OPERATOR',   'Operador',      'Registra ingresos, egresos, transferencias y conteos en sus bodegas'),
    ('AUDITOR',    'Auditor',       'Solo lectura: kárdex, reportes y bitácora de auditoría');

CREATE TABLE app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254) NOT NULL,
    full_name     varchar(120) NOT NULL,
    password_hash varchar(100) NOT NULL,
    role_code     varchar(20)  NOT NULL REFERENCES role (code),
    active        boolean      NOT NULL DEFAULT true,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    version       bigint       NOT NULL DEFAULT 0,
    CONSTRAINT uk_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email_lower CHECK (email = lower(email))
);

CREATE TABLE category (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code   varchar(20) NOT NULL,
    name   varchar(80) NOT NULL,
    active boolean     NOT NULL DEFAULT true,
    CONSTRAINT uk_category_code UNIQUE (code),
    CONSTRAINT ck_category_code CHECK (code ~ '^[A-Z0-9_-]{2,20}$')
);

CREATE TABLE unit_of_measure (
    code varchar(3)  PRIMARY KEY,
    name varchar(40) NOT NULL
);

