CREATE TABLE product (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            varchar(40)  NOT NULL,
    gtin           varchar(14),
    name           varchar(150) NOT NULL,
    description    varchar(500),
    category_id    bigint       NOT NULL REFERENCES category (id),
    base_uom_code  varchar(3)   NOT NULL REFERENCES unit_of_measure (code),
    lot_controlled boolean      NOT NULL DEFAULT false,
    abc_class      varchar(1)   NOT NULL DEFAULT 'C',
    active         boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    version        bigint       NOT NULL DEFAULT 0,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT uk_product_gtin UNIQUE (gtin),
    CONSTRAINT ck_product_sku CHECK (sku ~ '^[A-Z0-9][A-Z0-9._-]{1,39}$'),
    CONSTRAINT ck_product_gtin CHECK (gtin IS NULL OR gtin ~ '^[0-9]{14}$'),
    CONSTRAINT ck_product_abc CHECK (abc_class IN ('A', 'B', 'C'))
);

CREATE INDEX ix_product_category ON product (category_id);
CREATE INDEX ix_product_name ON product (lower(name));

CREATE TABLE product_uom_conversion (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint        NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    uom_code   varchar(3)    NOT NULL REFERENCES unit_of_measure (code),
    factor     numeric(18,6) NOT NULL,
    gtin       varchar(14),
    CONSTRAINT uk_conversion_product_uom UNIQUE (product_id, uom_code),
    CONSTRAINT uk_conversion_gtin UNIQUE (gtin),
    CONSTRAINT ck_conversion_factor CHECK (factor > 0),
    CONSTRAINT ck_conversion_gtin CHECK (gtin IS NULL OR gtin ~ '^[0-9]{14}$')
);
